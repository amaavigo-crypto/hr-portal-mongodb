/**
 * Writes docs/DATABASE_SCHEMA.md from the schemas in api/_lib/schemas, so the document can never drift from the code.
 *   npm run schema:doc            write the file
 *   npm run schema:doc -- --check exit with an error if the file is out of date (used by tests/schema.doc.test.ts)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { SCHEMAS, indexesFor, HIRING_KINDS, HRBP_KINDS } from '../api/_lib/schemas/index.ts';

const OUT = 'docs/DATABASE_SCHEMA.md';

function typeOf(p: any): string {
  const inst = p.instance as string;
  if (inst === 'Array') {
    const inner = p.caster?.instance || p.getEmbeddedSchemaType?.()?.instance;
    return `${inner && inner !== "Mixed" ? String(inner).toLowerCase() : "object"}[]`;
  }
  if (inst === 'Mixed') return 'object';
  return String(inst).toLowerCase();
}

export function render(): string {
  const names = Object.keys(SCHEMAS).sort();
  const lines: string[] = [];
  lines.push('# Database schema', '');
  lines.push('<!-- Generated by `npm run schema:doc` from api/_lib/schemas. Do not edit by hand. -->', '');
  lines.push(`The database is MongoDB, reached through the Firestore-shaped adapter in \`api/_lib/mongoFirestore.ts\`. There are **${names.length} collections**. This file lists each one with the fields its schema names. Schemas are \`strict: false\`: other fields may exist and are kept.`, '');
  lines.push('Conventions: the document id is stored as `_id` (a string) and is not a field below; many documents also copy it as `id`. Dates are ISO-8601 strings (`YYYY-MM-DD` or full timestamps). Every tenant-owned record has `companyId`. Fields marked *required* are checked on full writes (see `SCHEMA_VALIDATION` in the README).', '');
  lines.push('## Collections', '');
  for (const n of names) lines.push(`- [\`${n}\`](#${n.toLowerCase()})`);
  lines.push('');
  for (const n of names) {
    const def = SCHEMAS[n];
    lines.push(`## ${n}`, '', def.about, '');
    const rows: string[] = [];
    def.schema.eachPath((path: string, p: any) => {
      const enums: string[] | undefined = p.enumValues && p.enumValues.length ? p.enumValues : undefined;
      const req = p.isRequired ? 'required' : '';
      rows.push(`| \`${path}\` | ${typeOf(p)} | ${req} | ${enums ? enums.map((e) => `\`${e || "''"}\``).join(', ') : ''} |`);
    });
    if (rows.length) lines.push('| Field | Type | | Allowed values |', '| --- | --- | --- | --- |', ...rows, '');
    const idx = indexesFor(n).map(([f]) => `\`{ ${Object.entries(f).map(([k, v]) => `${k}: ${v}`).join(', ')} }\``);
    lines.push(`Indexes: ${idx.join(', ')}`, '');
    if (def.kinds) lines.push(`Extra rules by \`kind\`: ${Object.keys(def.kinds).map((k) => `\`${k}\``).join(', ')}`, '');
    if (n === 'hiringItems') lines.push(`Known \`kind\` values: ${HIRING_KINDS.map((k) => `\`${k}\``).join(', ')}`, '');
    if (n === 'hrbpItems') lines.push(`Known \`kind\` values: ${HRBP_KINDS.map((k) => `\`${k}\``).join(', ')}`, '');
  }
  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

if (process.argv[1]?.endsWith('gen-schema-doc.ts')) {
  const text = render();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (current !== text) { console.error(`${OUT} is out of date. Run: npm run schema:doc`); process.exit(1); }
    console.log(`${OUT} is up to date`);
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT}`);
  }
}
